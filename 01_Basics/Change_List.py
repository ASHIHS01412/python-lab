#Change Item Value
ashish = ["Smart", "handsome" , "good looking", "Intelligent" ]
ashish[1] = "Kind"
print(ashish)

#Change a Range of Item Values

ashish[1:3] = ["handsome","kind"]
print(ashish)


ashish[1:2] = ["problem-solving","Motivated "]
print(ashish)

ashish[1:3] = ["god"]
print(ashish)

#Insert Items

ashish.insert(2,"good looking")
print(ashish)